CREATE TABLE IF NOT EXISTS communities (
      id TEXT PRIMARY KEY, name TEXT NOT NULL, description TEXT NOT NULL,
      color TEXT NOT NULL, icon TEXT NOT NULL, members INTEGER NOT NULL DEFAULT 0
    );

CREATE TABLE IF NOT EXISTS profiles (id TEXT PRIMARY KEY, name TEXT NOT NULL, bio TEXT NOT NULL DEFAULT '', email TEXT, password_hash TEXT, role TEXT NOT NULL DEFAULT 'user', suspended INTEGER NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS posts (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, community TEXT NOT NULL REFERENCES communities(id),
      author TEXT NOT NULL, initials TEXT NOT NULL, title TEXT NOT NULL, body TEXT NOT NULL,
      tag TEXT NOT NULL, visual TEXT, created_at BIGINT NOT NULL, base_score INTEGER NOT NULL DEFAULT 0,
      owner TEXT REFERENCES profiles(id)
    , removed INTEGER NOT NULL DEFAULT 0, locked INTEGER NOT NULL DEFAULT 0, edited_at BIGINT, revision INTEGER NOT NULL DEFAULT 0, answer_revision INTEGER NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS post_images (
  id TEXT PRIMARY KEY, owner TEXT NOT NULL REFERENCES profiles(id),
  post_id INTEGER REFERENCES posts(id) ON DELETE CASCADE, data BYTEA NOT NULL,
  width INTEGER NOT NULL, height INTEGER NOT NULL, alt TEXT NOT NULL DEFAULT '',
  position INTEGER NOT NULL DEFAULT 0, created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS post_images_post ON post_images(post_id,position);
CREATE INDEX IF NOT EXISTS post_images_owner ON post_images(owner);

CREATE TABLE IF NOT EXISTS votes (
      user_id TEXT NOT NULL REFERENCES profiles(id), post_id INTEGER NOT NULL REFERENCES posts(id),
      value INTEGER NOT NULL CHECK(value IN (-1, 1)), PRIMARY KEY(user_id, post_id)
    );

CREATE TABLE IF NOT EXISTS saves (
      user_id TEXT NOT NULL REFERENCES profiles(id), post_id INTEGER NOT NULL REFERENCES posts(id), PRIMARY KEY(user_id, post_id)
    );

CREATE TABLE IF NOT EXISTS memberships (
      user_id TEXT NOT NULL REFERENCES profiles(id), community TEXT NOT NULL REFERENCES communities(id), PRIMARY KEY(user_id, community)
    );

CREATE TABLE IF NOT EXISTS comments (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, post_id INTEGER NOT NULL REFERENCES posts(id),
      author TEXT NOT NULL, body TEXT NOT NULL, created_at BIGINT NOT NULL, owner TEXT REFERENCES profiles(id)
    , removed INTEGER NOT NULL DEFAULT 0, parent_id INTEGER REFERENCES comments(id), edited_at BIGINT, revision INTEGER NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS comment_votes (
      user_id TEXT NOT NULL REFERENCES profiles(id),
      comment_id INTEGER NOT NULL REFERENCES comments(id) ON DELETE CASCADE,
      value INTEGER NOT NULL CHECK(value IN (-1, 1)),
      PRIMARY KEY(user_id, comment_id)
    );

CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES profiles(id), expires_at BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS recovery_codes (code_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES profiles(id));

CREATE TABLE IF NOT EXISTS rate_limits (key TEXT PRIMARY KEY, attempts INTEGER NOT NULL, expires_at BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS reports (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reporter TEXT NOT NULL REFERENCES profiles(id),
      target_type TEXT NOT NULL CHECK(target_type IN ('post','comment')), target_id INTEGER NOT NULL,
      reason TEXT NOT NULL, details TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'open', created_at BIGINT NOT NULL
    );

CREATE TABLE IF NOT EXISTS moderation_log (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor TEXT NOT NULL REFERENCES profiles(id), action TEXT NOT NULL,
      target_type TEXT NOT NULL, target_id TEXT NOT NULL, reason TEXT NOT NULL, created_at BIGINT NOT NULL
    );

CREATE TABLE IF NOT EXISTS notifications (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      recipient TEXT NOT NULL REFERENCES profiles(id),
      comment_id INTEGER NOT NULL REFERENCES comments(id),
      kind TEXT NOT NULL CHECK(kind IN ('reply','comment')),
      created_at BIGINT NOT NULL, read_at BIGINT,
      UNIQUE(recipient,comment_id)
    );
