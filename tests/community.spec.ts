test('votes, bookmarks, and memberships persist and belong to each visitor', async ({ request, playwright }) => {
  const initial = await (await request.get('/api/community')).json();
  const post = initial.posts[0];
  const vote = await request.post('/api/community', { data: { action: 'vote', postId: post.id, value: 1 } });
  expect(vote.ok()).toBeTruthy();
  let state = await (await request.get('/api/community')).json();
  expect(state.posts.find((p: { id: number }) => p.id === post.id)).toMatchObject({ score: post.score + 1, vote: 1 });
  await request.post('/api/community', { data: { action: 'vote', postId: post.id, value: 1 } });
  state = await (await request.get('/api/community')).json();
  expect(state.posts.find((p: { id: number }) => p.id === post.id).score).toBe(post.score + 1);
  await request.post('/api/community', { data: { action: 'save', postId: post.id, value: true } });
  await request.post('/api/community', { data: { action: 'join', community: 'developers', value: true } });
  state = await (await request.get('/api/community')).json();
  expect(state.posts.find((p: { id: number }) => p.id === post.id).saved).toBe(1);
  expect(state.communities.find((c: { id: string }) => c.id === 'developers').joined).toBe(1);
  const other = await playwright.request.newContext({ baseURL: 'http://127.0.0.1:3100' });
  const otherState = await (await other.get('/api/community')).json();
  expect(otherState.posts.find((p: { id: number }) => p.id === post.id)).toMatchObject({ vote: 0, saved: 0 });
  expect(otherState.communities.find((c: { id: string }) => c.id === 'developers').joined).toBe(0);
  await other.dispose();
  await request.post('/api/community', { data: { action: 'vote', postId: post.id, value: 0 } });
  state = await (await request.get('/api/community')).json();
  expect(state.posts.find((p: { id: number }) => p.id === post.id).score).toBe(post.score);
});

test('rejects invalid posts, unknown post IDs, invalid votes, and cross-origin changes', async ({ request }) => {
  const invalidPost = await request.post('/api/community', { data: { action: 'post', title: 'x', body: '', community: 'salesforce', tag: 'Discussion' } });
  expect(invalidPost.status()).toBe(400);
  const missing = await request.post('/api/community', { data: { action: 'vote', postId: 9999999, value: 1 } });
  expect(missing.status()).toBe(404);
  const invalidVote = await request.post('/api/community', { data: { action: 'vote', postId: 1, value: 2 } });
  expect(invalidVote.status()).toBe(400);
  const crossOrigin = await request.post('/api/community', { headers: { Origin: 'https://untrusted.example' }, data: { action: 'profile', name: 'Changed name' } });
  expect(crossOrigin.status()).toBe(403);
});

