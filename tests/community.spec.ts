test('threads are full pages with working links, browser history, reload, and document scrolling', async ({ page, request }) => {
  for (let index = 1; index <= 12; index++) {
    await request.post('/api/community', { data: { action: 'comment', postId: 1, body: `Page scrolling regression comment ${index}. A useful discussion should stay readable all the way to the last reply.` } });
  }
  await page.setViewportSize({ width: 1280, height: 650 });
  await page.goto('/');
  const postLink = page.getByRole('link', { name: 'The little Salesforce things that made a big difference this week', exact: true });
  await expect(postLink).toHaveAttribute('href', '/posts/1');
  await postLink.click();
  await expect(page).toHaveURL(/\/posts\/1$/);
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('The little Salesforce things that made a big difference this week');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('.comment')).toHaveCount(15);
  await page.mouse.move(650, 480);
  await page.mouse.wheel(0, 1100);
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(500);
  await page.locator('.comment').last().scrollIntoViewIfNeeded();
  await expect(page.locator('.comment').last()).toBeInViewport();
  await page.reload();
  await expect(page.locator('.comment')).toHaveCount(15);
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.goBack();
  await expect(page).toHaveURL('http://127.0.0.1:3100/');
  await expect(postLink).toBeVisible();
  await page.goForward();
  await expect(page).toHaveURL(/\/posts\/1$/);
  await expect(page.locator('.comment')).toHaveCount(15);
  await page.goto('/?post=1');
  await expect(page).toHaveURL(/\/posts\/1$/);
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.goto('/posts/1#comments');
  await expect(page.getByRole('heading', { name: 'Join the conversation 15' })).toBeInViewport();
  await page.setViewportSize({ width: 390, height: 600 });
  await page.locator('.comment').last().scrollIntoViewIfNeeded();
  await expect(page.locator('.comment').last()).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.getByRole('link', { name: 'Back to feed', exact: true }).click();
  await expect(page).toHaveURL('http://127.0.0.1:3100/');
});

test('remaining dialogs scroll within a small viewport and keep their close button reachable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 550 });
  await page.goto('/');
  await expect(page.locator('.post-card').first()).toBeVisible();
  await page.getByRole('button', { name: 'Create post', exact: true }).click();
  const dialog = page.getByRole('dialog');
  const body = dialog.locator('.dialog-body');
  const bounds = await dialog.boundingBox();
  expect(bounds!.y).toBeGreaterThanOrEqual(0);
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(550);
  expect(await body.evaluate(el => el.scrollHeight > el.clientHeight)).toBeTruthy();
  await page.mouse.move(200, 350);
  await page.mouse.wheel(0, 900);
  await expect.poll(() => body.evaluate(el => el.scrollTop)).toBeGreaterThan(0);
  await expect(page.getByRole('button', { name: 'Publish post', exact: true })).toBeInViewport();
  await expect(page.getByRole('button', { name: 'Close dialog' })).toBeInViewport();
  expect(await page.evaluate(() => window.scrollY)).toBe(0);
  await page.getByRole('button', { name: 'Close dialog' }).click();
  expect(await page.evaluate(() => document.documentElement.style.overflow)).toBe('');
  await page.getByRole('button', { name: 'Find your community', exact: true }).click();
  await page.mouse.move(200, 350);
  await page.mouse.wheel(0, 1600);
  await expect.poll(() => body.evaluate(el => el.scrollTop)).toBeGreaterThan(0);
  await dialog.getByRole('button', { name: 'Flow Builders', exact: true }).scrollIntoViewIfNeeded();
  await expect(dialog.getByRole('button', { name: 'Flow Builders', exact: true })).toBeInViewport();
  await expect(page.getByRole('button', { name: 'Close dialog' })).toBeInViewport();
});
