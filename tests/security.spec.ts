import {test,expect,type APIRequestContext} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import {DatabaseSync} from 'node:sqlite';
import {randomUUID} from 'node:crypto';
import {register,password} from './fixtures';
const post=(r:APIRequestContext,url:string,data:Record<string,unknown>)=>r.post(url,{data});
const account=(r:APIRequestContext,data:Record<string,unknown>)=>post(r,'/api/account',data);
const community=(r:APIRequestContext,data:Record<string,unknown>)=>post(r,'/api/community',data);
const moderate=(r:APIRequestContext,data:Record<string,unknown>)=>post(r,'/api/moderation',data);
function promote(email:string){execFileSync(process.execPath,['scripts/admin.mjs',email],{env:{...process.env,DATABASE_PATH:process.env.TEST_DATABASE_PATH},stdio:'pipe'});}

test('credentials, hashed secrets, session isolation, recovery rotation and replay protection',async({request,playwright})=>{
  expect((await community(request,{action:'vote',postId:1,value:1})).status()).toBe(401);
  expect((await request.get('/api/moderation')).status()).toBe(401);
  expect((await request.post('/api/account',{headers:{Origin:'https://evil.example'},data:{action:'register'}})).status()).toBe(403);
  expect((await account(request,{action:'register',email:'bad@example.com',name:'Test',password:'short'})).status()).toBe(400);
  const identity=await register(request,'Recovery Tester');
  expect(identity.codes).toHaveLength(5);
  const state=await (await request.get('/api/community')).json();
  expect(state.profile).toMatchObject({registered:1,email:identity.email,role:'user'});
  expect(state.posts[0]).not.toHaveProperty('owner');
  expect(state.profile).not.toHaveProperty('password_hash');
  const cookie=(await request.storageState()).cookies.find(c=>c.name==='trailtalk_session')!;
  expect(cookie.httpOnly).toBe(true);expect(cookie.sameSite).toBe('Lax');
  const d=new DatabaseSync(process.env.TEST_DATABASE_PATH!);
  const stored=d.prepare('SELECT id,password_hash FROM profiles WHERE email=?').get(identity.email)!;
  expect(stored.password_hash).not.toContain(password);
  expect(d.prepare('SELECT token_hash FROM sessions WHERE token_hash=?').get(cookie.value)).toBeUndefined();
  expect(d.prepare('SELECT code_hash FROM recovery_codes WHERE code_hash=?').get(identity.codes[0])).toBeUndefined();
  d.close();
  const second=await playwright.request.newContext({baseURL:'http://127.0.0.1:3100'});
  try{
    expect((await account(second,{action:'login',email:identity.email,password:'Wrong passphrase 123!'})).status()).toBe(401);
    expect((await account(second,{action:'login',email:identity.email,password})).ok()).toBe(true);
    expect((await account(second,{action:'regenerateCodes',currentPassword:'Wrong passphrase 123!'})).status()).toBe(401);
    const next='My recovered passphrase 987!';
    const resets=await Promise.all([request,second].map(r=>account(r,{action:'recover',email:identity.email,code:identity.codes[0],password:next})));
    expect(resets.map(r=>r.status()).sort()).toEqual([200,401]);
    const newCodes=(await resets.find(r=>r.status()===200)!.json()).codes;
    expect(newCodes).toHaveLength(5);
    for(const r of [request,second]) expect((await community(r,{action:'vote',postId:1,value:1})).status()).toBe(401);
    expect((await account(request,{action:'recover',email:identity.email,code:identity.codes[1],password:next})).status()).toBe(401);
    expect((await account(request,{action:'login',email:identity.email,password})).status()).toBe(401);
    expect((await account(request,{action:'login',email:identity.email,password:next})).status()).toBe(200);
    const changed=await account(request,{action:'changePassword',currentPassword:next,password:'My changed passphrase 567!'});
    expect(changed.status()).toBe(200);
    expect((await community(request,{action:'vote',postId:1,value:1})).status()).toBe(401);
    expect((await account(request,{action:'recover',email:identity.email,code:newCodes[0],password:next})).status()).toBe(401);
    expect((await account(request,{action:'login',email:identity.email,password:'My changed passphrase 567!'})).status()).toBe(200);
    const session=(await request.storageState()).cookies;
    await account(request,{action:'logout'});
    const replay=await playwright.request.newContext({baseURL:'http://127.0.0.1:3100',storageState:{cookies:session,origins:[]}});
    expect((await community(replay,{action:'vote',postId:1,value:1})).status()).toBe(401);await replay.dispose();
  }finally{await second.dispose();}
});

test('login and recovery attempts are limited without exposing account existence',async({request})=>{
  const email=`unknown-${randomUUID()}@example.com`;
  for(let n=0;n<10;n++)expect((await account(request,{action:'login',email,password})).status()).toBe(401);
  expect((await account(request,{action:'login',email,password})).status()).toBe(429);
  for(let n=0;n<10;n++)expect((await account(request,{action:'recover',email,password,code:'invalid'})).status()).toBe(401);
  expect((await account(request,{action:'recover',email,password,code:'invalid'})).status()).toBe(429);
});

test('moderation permissions, reports, removal/restoration, locks, suspension and audit history',async({request,playwright})=>{
  const admin=await register(request,'Test Administrator');promote(admin.email);
  const member=await playwright.request.newContext({baseURL:'http://127.0.0.1:3100'});
  const mod=await playwright.request.newContext({baseURL:'http://127.0.0.1:3100'});
  try{
    const identity=await register(member,'Moderated Member');const modIdentity=await register(mod,'Moderator Tester');
    const created=await community(member,{action:'post',title:'Moderation test conversation',body:'This is content used to test real moderation actions.',community:'salesforce',tag:'Discussion'});
    const id=(await created.json()).createdId;
    expect(created.status()).toBe(200);
    await community(member,{action:'comment',postId:id,body:'A comment to review and restore.'});
    const commentId=(await (await member.get(`/api/community?post=${id}`)).json()).comments[0].id;
    expect((await member.get('/api/moderation')).status()).toBe(403);
    expect((await moderate(member,{action:'remove',targetType:'post',targetId:id,reason:'No authority'})).status()).toBe(403);
    for(let n=0;n<2;n++)expect((await moderate(member,{action:'report',targetType:'post',targetId:id,reason:'Spam',details:'Repeated advertising.'})).status()).toBe(200);
    let queue=await(await request.get('/api/moderation')).json();
    expect(queue.reports.filter((r:{target_id:number;target_type:string})=>r.target_id===id&&r.target_type==='post')).toHaveLength(1);
    const memberId=queue.users.find((u:{name:string})=>u.name==='Moderated Member').id;
    const modId=queue.users.find((u:{name:string})=>u.name==='Moderator Tester').id;
    const adminId=queue.users.find((u:{name:string})=>u.name==='Test Administrator').id;
    expect((await moderate(request,{action:'role',userId:modId,role:'moderator',reason:'Appointed to review reports'})).status()).toBe(200);
    expect((await mod.get('/api/moderation')).status()).toBe(200);
    expect((await moderate(mod,{action:'role',userId:memberId,role:'moderator',reason:'Unauthorized role grant'})).status()).toBe(403);
    expect((await moderate(mod,{action:'suspend',userId:adminId,reason:'Cannot suspend administrator'})).status()).toBe(403);
    expect((await moderate(mod,{action:'suspend',userId:modId,reason:'Cannot suspend yourself'})).status()).toBe(403);
    expect((await moderate(mod,{action:'lock',targetType:'post',targetId:id,reason:'Pause the discussion'})).status()).toBe(200);
    expect((await community(member,{action:'comment',postId:id,body:'Should not be posted'})).status()).toBe(403);
    expect((await moderate(mod,{action:'unlock',targetType:'post',targetId:id,reason:'Discussion can resume'})).status()).toBe(200);
    expect((await moderate(mod,{action:'remove',targetType:'comment',targetId:commentId,reason:'Comment breaks the rules'})).status()).toBe(200);
    const publicComment=(await(await member.get(`/api/community?post=${id}`)).json()).comments[0];
    expect(publicComment.body).toBe('[Removed by moderators]');
    expect((await community(member,{action:'commentVote',commentId,value:1})).status()).toBe(404);
    expect((await moderate(mod,{action:'restore',targetType:'comment',targetId:commentId,reason:'Review confirmed comment is valid'})).status()).toBe(200);
    expect((await(await member.get(`/api/community?post=${id}`)).json()).comments[0].body).toBe('A comment to review and restore.');
    expect((await moderate(mod,{action:'remove',targetType:'post',targetId:id,reason:'Post breaks community rules'})).status()).toBe(200);
    expect((await member.get(`/posts/${id}`)).status()).toBe(404);
    expect((await member.get(`/api/community?post=${id}`)).status()).toBe(404);
    expect((await community(member,{action:'vote',postId:id,value:1})).status()).toBe(404);
    expect((await(await member.get('/api/community')).json()).posts.some((p:{id:number})=>p.id===id)).toBe(false);
    expect((await moderate(mod,{action:'restore',targetType:'post',targetId:id,reason:'Appeal accepted after review'})).status()).toBe(200);
    expect((await moderate(mod,{action:'suspend',userId:memberId,reason:'Repeated rule violations'})).status()).toBe(200);
    expect((await community(member,{action:'vote',postId:id,value:1})).status()).toBe(403);
    expect((await moderate(member,{action:'report',targetType:'post',targetId:id,reason:'Spam'})).status()).toBe(403);
    const reset=await account(member,{action:'recover',email:identity.email,code:identity.codes[0],password});expect(reset.status()).toBe(200);
    expect((await account(member,{action:'login',email:identity.email,password})).status()).toBe(200);
    expect((await community(member,{action:'comment',postId:id,body:'Recovery cannot bypass suspension'})).status()).toBe(403);
    expect((await moderate(mod,{action:'unsuspend',userId:memberId,reason:'Suspension has been reviewed'})).status()).toBe(200);
    expect((await community(member,{action:'comment',postId:id,body:'Access has been restored'})).status()).toBe(200);
    await moderate(member,{action:'report',targetType:'comment',targetId:commentId,reason:'Other'});
    queue=await(await request.get('/api/moderation')).json();
    const report=queue.reports.find((r:{target_id:number;target_type:string})=>r.target_id===commentId&&r.target_type==='comment');
    expect((await moderate(mod,{action:'dismiss',reportId:report.id,reason:'Comment complies with the rules'})).status()).toBe(200);
    queue=await(await request.get('/api/moderation')).json();
    expect(queue.reports.find((r:{id:number})=>r.id===report.id).status).toBe('dismissed');
    expect(queue.log.some((l:{action:string;reason:string})=>l.action==='suspend'&&l.reason==='Repeated rule violations')).toBe(true);
    expect(queue.reports.find((r:{target_type:string;target_id:number})=>r.target_type==='post'&&r.target_id===id).status).toBe('actioned');
    expect((await moderate(request,{action:'role',userId:modId,role:'user',reason:'Assignment ended'})).status()).toBe(200);
    expect((await mod.get('/api/moderation')).status()).toBe(403);
    expect(modIdentity.codes).toHaveLength(5);
  }finally{await member.dispose();await mod.dispose();}
});

